// Bundles web/src/bookmarklet/collector-entry.ts into one minified expression and writes
// web/src/bookmarklet/generated.ts (gitignored; built before vite build, tests and typechecks).
// The app address is filled in at run time (bookmarkletHref) so the same build works on localhost and on Pages.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Script } from 'node:vm';
import { build } from 'esbuild';

const root = join(import.meta.dirname, '..');
const result = await build({
  entryPoints: [join(root, 'web/src/bookmarklet/collector-entry.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  write: false,
  legalComments: 'none',
  logLevel: 'warning',
});
// esbuild marks modules strict with a directive; inside void(…) that would be a syntax error.
const js = (result.outputFiles[0]?.text ?? '')
  .trim()
  .replace(/^"use strict";\s*/, '')
  .replace(/;$/, '');
if (!js.includes('__NCM_APP_URL__'))
  throw new Error('The app URL placeholder was lost in the bundle');

// Wrapped in void(): otherwise the expression's value (a Promise) can replace the current page in some browsers.
const body = `void(${js})`;
// Compile it (without running it): a bookmarklet that cannot parse must never ship.
new Script(body);
const dir = join(root, 'web/src/bookmarklet');
mkdirSync(dir, { recursive: true });
writeFileSync(
  join(dir, 'generated.ts'),
  `// Generated by scripts/build-bookmarklet.ts. Do not edit; do not commit.\nexport const BOOKMARKLET_BODY = ${JSON.stringify(body)};\n`,
);
console.log(`bookmarklet: ${body.length} bytes`);
